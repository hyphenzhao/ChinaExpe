def hidden_kind(branch: str, stem: str) -> str:
    """本气 / 中气 / 余气，按权重大小判定。"""
    ranked = sorted(HIDDEN_WEIGHT[branch].items(), key=lambda kv: -kv[1])
    names = ["本气", "中气", "余气"]
    for i, (s, _) in enumerate(ranked):
        if s == stem:
            return names[i]
    return ""


